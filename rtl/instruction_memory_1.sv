module instruction_memory_1(
			  input logic [31:0]  address,
			  input logic	      reset,
			  output logic [31:0] instruction
			  );
   logic [31:0]				      Memory [0:45];

   initial begin
      // === 초기화 ===
      Memory[0]  = 32'b001000_00000_01011_00000_00000_000000; // addi $t10, $zero, 0
      Memory[1]  = 32'b101011_00000_01011_00000_00001_000000; // sw $t10, 16($zero)

      // === 루프 시작 ===
      Memory[2]  = 32'b100011_00000_00001_00000_00000_100000; // lw $t0, 8($zero)
      Memory[3]  = 32'b100011_00000_00010_00000_00000_000000; // lw $t1, 0($zero)
      Memory[4]  = 32'b100011_00000_00011_00000_00000_000100; // lw $t2, 1($zero)
      Memory[5]  = 32'b100011_00000_00100_00000_00000_001100; // lw $t3, 3($zero)

      Memory[6]  = 32'b100011_00000_00101_00000_00000_101000; // lw $t4, 10($zero)
      Memory[7]  = 32'b100011_00000_00110_00000_00000_101100; // lw $t5, 11($zero)
      Memory[8]  = 32'b100011_00000_00111_00000_00000_110100; // lw $t6, 13($zero)

      Memory[9]  = 32'b000000_00010_00101_01000_00000_100001; // mul $t7, $t1, $t4
      Memory[10] = 32'b000000_00011_00110_01001_00000_100001; // mul $t8, $t2, $t5
      Memory[11] = 32'b000000_00100_00111_01010_00000_100001; // mul $t9, $t3, $t6

      Memory[12] = 32'b000000_01000_01001_01110_00000_100000; // add $t13, $t7, $t8
      Memory[13] = 32'b000000_01110_01010_01110_00000_100000; // add $t13, $t13, $t9

      Memory[14] = 32'b000000_00001_01110_01111_00000_100010; // sub $t14, $t0, $t13

      Memory[15] = 32'b100011_00000_00010_00000_00000_001000; // lw $t1, 2($zero)
      Memory[16] = 32'b000000_01111_00010_10000_00000_100011; // div $t15, $t14, $t1
      Memory[17] = 32'b101011_00000_10000_00000_00000_111000; // sw $t15, 14($zero)

      Memory[18] = 32'b100011_00000_00001_00000_00000_100100; // lw $t0, 9($zero)
      Memory[19] = 32'b100011_00000_00010_00000_00000_010000; // lw $t1, 4($zero)
      Memory[20] = 32'b100011_00000_00011_00000_00000_010100; // lw $t2, 5($zero)
      Memory[21] = 32'b100011_00000_00100_00000_00000_011000; // lw $t3, 6($zero)

      Memory[22] = 32'b100011_00000_00101_00000_00000_101000; // lw $t4, 10($zero)
      Memory[23] = 32'b100011_00000_00110_00000_00000_101100; // lw $t5, 11($zero)
      Memory[24] = 32'b100011_00000_00111_00000_00000_110000; // lw $t6, 12($zero)

      Memory[25] = 32'b000000_00010_00101_01000_00000_100001; // mul $t7, $t1, $t4
      Memory[26] = 32'b000000_00011_00110_01001_00000_100001; // mul $t8, $t2, $t5
      Memory[27] = 32'b000000_00100_00111_01010_00000_100001; // mul $t9, $t3, $t6

      Memory[28] = 32'b000000_01000_01001_01110_00000_100000; // add $t13, $t7, $t8
      Memory[29] = 32'b000000_01110_01010_01110_00000_100000; // add $t13, $t13, $t9

      Memory[30] = 32'b000000_00001_01110_01111_00000_100010; // sub $t14, $t0, $t13

      Memory[31] = 32'b100011_00000_00010_00000_00000_011100; // lw $t1, 7($zero)
      Memory[32] = 32'b000000_01111_00010_10000_00000_100011; // div $t15, $t14, $t1
      Memory[33] = 32'b101011_00000_10000_00000_00000_111100; // sw $t15, 15($zero)

      Memory[34] = 32'b100011_00000_00001_00000_00000_111000; // lw $t0, 14($zero)
      Memory[35] = 32'b101011_00000_00001_00000_00000_110000; // sw $t0, 12($zero)
      Memory[36] = 32'b100011_00000_00010_00000_00000_111100; // lw $t1, 15($zero)
      Memory[37] = 32'b101011_00000_00010_00000_00000_110100; // sw $t1, 13($zero)

      Memory[38] = 32'b010101_00000_00000_00000_00000_000000; // rec x1(k), x2(k)

      Memory[39] = 32'b100011_00000_01011_00000_00001_000000; // lw $t10, 16($zero)
      Memory[40] = 32'b001000_01011_01011_00000_00000_000001; // addi $t10, $t10, 1
      Memory[41] = 32'b101011_00000_01011_00000_00001_000000; // sw $t10, 16($zero)

      Memory[42] = 32'b100011_00000_01100_00000_00001_000100; // lw $t11, 17($zero)

      // 비교: 루프 탈출 조건
      Memory[43] = 32'b000100_01100_01011_00000_00000_000001; // beq $t10, $t11, End  [fix] imm 180 -> 1 : BTA = PC+4 + (imm<<2) = 176 + 4 = 180

      Memory[44] = 32'b000010_00000_00000_00000_00000_000100; // j LoopStart

      // === 종료 ===
      Memory[45] = 32'b000010_00000_00000_00000_00010_110100; // j End

   end // initial begin

   always_comb begin
      if(!reset)
	instruction = 32'h00000000;
      else
	instruction = Memory[address[31:2]];
   end
endmodule // instruction_memory
